//! Generates Rust source (plain `&'static` data, no heap/dynamic
//! allocation - AUTOSAR static-configuration principle, see PLAN.md
//! "Architektur") from a parsed [`crate::Config`]. Issue #9.
//!
//! Also does the one semantic check `rosek-config`'s parser (issue #8)
//! deliberately left for this stage: every `TASK`'s `APPLICATION` must
//! name an actually-declared `OS_APPLICATION`. Syntax is #8's job,
//! cross-references between blocks are this module's.

use crate::{Config, Schedule};
use std::collections::HashSet;
use std::fmt;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    pub message: String,
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for CodegenError {}

/// Generates the full contents of a Rust source file defining `TaskConfig`/
/// `OsApplicationConfig` and the `TASKS`/`OS_APPLICATIONS` static arrays
/// built from `config`. Meant to be written to `$OUT_DIR/config.rs` and
/// pulled in via `include!` (see `rosek-board-beaglebone-black/build.rs`).
pub fn generate(config: &Config) -> Result<String, CodegenError> {
    check_application_references(config)?;

    let mut out = String::new();
    out.push_str(
        "// Generated by rosek-config from the board's .cfg file. Do not edit by hand.\n\n",
    );

    // #[allow(dead_code)] throughout: which enum variants/fields end up
    // actually read is a function of the *specific* board's rosek.cfg
    // content and of not-yet-existing consumers (the scheduler, Phase 3) -
    // never a sign of genuinely dead code in the generated schema itself.
    out.push_str(
        "#[allow(dead_code)]\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum ScheduleConfig { Full, Non }\n\n",
    );
    out.push_str(
        "#[allow(dead_code)]\n#[derive(Debug, Clone, Copy)]\npub struct TaskConfig {\n    pub name: &'static str,\n    pub priority: u32,\n    pub schedule: ScheduleConfig,\n    pub application: &'static str,\n}\n\n",
    );
    out.push_str(
        "#[allow(dead_code)]\n#[derive(Debug, Clone, Copy)]\npub struct OsApplicationConfig {\n    pub name: &'static str,\n    pub trusted: bool,\n}\n\n",
    );

    out.push_str("pub static TASKS: &[TaskConfig] = &[\n");
    for task in &config.tasks {
        let schedule = match task.schedule {
            Schedule::Full => "ScheduleConfig::Full",
            Schedule::Non => "ScheduleConfig::Non",
        };
        out.push_str(&format!(
            "    TaskConfig {{ name: {:?}, priority: {}, schedule: {}, application: {:?} }},\n",
            task.name, task.priority, schedule, task.application
        ));
    }
    out.push_str("];\n\n");

    out.push_str("pub static OS_APPLICATIONS: &[OsApplicationConfig] = &[\n");
    for app in &config.os_applications {
        out.push_str(&format!(
            "    OsApplicationConfig {{ name: {:?}, trusted: {} }},\n",
            app.name, app.trusted
        ));
    }
    out.push_str("];\n");

    Ok(out)
}

fn check_application_references(config: &Config) -> Result<(), CodegenError> {
    let known: HashSet<&str> = config
        .os_applications
        .iter()
        .map(|a| a.name.as_str())
        .collect();
    for task in &config.tasks {
        if !known.contains(task.application.as_str()) {
            return Err(CodegenError {
                message: format!(
                    "TASK {} references APPLICATION {}, which has no OS_APPLICATION block",
                    task.name, task.application
                ),
            });
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{OsApplication, Task};

    fn sample_config() -> Config {
        Config {
            tasks: vec![Task {
                name: "MainTask".into(),
                priority: 5,
                schedule: Schedule::Full,
                application: "TrustedApp".into(),
            }],
            os_applications: vec![OsApplication {
                name: "TrustedApp".into(),
                trusted: true,
            }],
        }
    }

    #[test]
    fn generates_valid_looking_rust_source() {
        let src = generate(&sample_config()).unwrap();
        assert!(src.contains("pub static TASKS: &[TaskConfig] = &["));
        assert!(src.contains(r#"name: "MainTask""#));
        assert!(src.contains("priority: 5"));
        assert!(src.contains("schedule: ScheduleConfig::Full"));
        assert!(src.contains(r#"application: "TrustedApp""#));
        assert!(src.contains(r#"name: "TrustedApp", trusted: true"#));
    }

    #[test]
    fn empty_config_generates_empty_arrays() {
        let src = generate(&Config::default()).unwrap();
        assert!(src.contains("pub static TASKS: &[TaskConfig] = &[\n];"));
        assert!(src.contains("pub static OS_APPLICATIONS: &[OsApplicationConfig] = &[\n];"));
    }

    #[test]
    fn os_application_with_no_referencing_task_is_fine() {
        // An OS-Application that no TASK currently references is not an
        // error - only the reverse (a TASK pointing at a nonexistent
        // OS-Application) is.
        let mut config = sample_config();
        config.os_applications.push(OsApplication {
            name: "UnusedApp".into(),
            trusted: false,
        });
        let src = generate(&config).unwrap();
        assert!(src.contains(r#"name: "UnusedApp", trusted: false"#));
    }

    #[test]
    fn generates_multiple_tasks_and_applications_in_declaration_order() {
        let config = Config {
            tasks: vec![
                Task {
                    name: "A".into(),
                    priority: 1,
                    schedule: Schedule::Full,
                    application: "App1".into(),
                },
                Task {
                    name: "B".into(),
                    priority: 2,
                    schedule: Schedule::Non,
                    application: "App2".into(),
                },
            ],
            os_applications: vec![
                OsApplication {
                    name: "App1".into(),
                    trusted: true,
                },
                OsApplication {
                    name: "App2".into(),
                    trusted: false,
                },
            ],
        };
        let src = generate(&config).unwrap();
        let a_pos = src.find(r#"name: "A""#).unwrap();
        let b_pos = src.find(r#"name: "B""#).unwrap();
        assert!(a_pos < b_pos, "tasks should appear in declaration order");
        assert!(src.contains("ScheduleConfig::Non"));
    }

    #[test]
    fn rejects_task_referencing_unknown_application() {
        let mut config = sample_config();
        config.tasks[0].application = "DoesNotExist".into();
        let err = generate(&config).unwrap_err();
        assert!(err.message.contains("DoesNotExist"));
        assert!(err.message.contains("MainTask"));
    }

    #[test]
    fn generated_source_actually_compiles_and_matches_the_config() {
        // Strongest check available here: actually invoke rustc on the
        // generated string and confirm it produces a valid object file,
        // not just "contains the right substrings".
        let src = generate(&sample_config()).unwrap();
        let dir =
            std::env::temp_dir().join(format!("rosek_config_codegen_test_{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let src_path = dir.join("generated.rs");
        std::fs::write(&src_path, src).unwrap();

        let out_path = dir.join("generated.o");
        let status = std::process::Command::new("rustc")
            .args(["--crate-type", "lib", "--emit", "obj", "-o"])
            .arg(&out_path)
            .arg(&src_path)
            .status()
            .expect("failed to invoke rustc");
        assert!(status.success(), "generated code did not compile");

        std::fs::remove_dir_all(&dir).ok();
    }
}
